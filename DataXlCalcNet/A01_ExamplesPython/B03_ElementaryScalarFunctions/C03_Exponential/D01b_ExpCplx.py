def demo_exp_cplx_ctx():
    print('<H1 Title="exp_cplx_ctx">')
    xlist = [-5.1+2j, 8.8+2j]; gui.setdps(50)
    for x in xlist:
        print('<H2 Title="exp(x); x=' + str(x) + '">')
