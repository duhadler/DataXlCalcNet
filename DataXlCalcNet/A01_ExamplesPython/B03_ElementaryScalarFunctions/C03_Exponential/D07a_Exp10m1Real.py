def main_tests():
    demo_manual_real()
    demo_exp10m1_real_ctx()
    demo_exp10m1_real_explicit()


def demo_manual_real():
    print('<H1 Title="demo_manual_real">')
    #from xlcalcnet import *
    x = -5.1; gui.setdps(90)
    for ctx in gui.ctxlist_real: print(ctx.fmtname + ': ' + ctx.fmt(ctx.exp10m1(x)))
    print('</H1>')


def demo_exp10m1_real_ctx():
    print('<H1 Title="demo_exp10m1_real_ctx">')
    xlist = [-5.1, 8.8]; gui.setdps(90)
    for x in xlist:
        print('<H2 Title="exp10m1(x); x=' + str(x) + '">')
        for ctx in gui.ctxlist_real:
            res = ctx.exp10m1(x)
            print(ctx.fmtname + ': ' + ctx.fmt(res))
        print('</H2>')
        print()
    print('</H1>')
    print()


def demo_exp10m1_real_explicit():
    print('<H1 Title="demo_exp10m1_real_explicit">')
    xlist = [-5.1, 8.8]; gui.setdps(90)
    for x in xlist:
        print('<H2 Title="exp10m1(x); x=' + str(x) + '">')
        res = math53.exp10m1(x); print('math53: ' + math53.fmt(res))
        res = sreal.exp10m1(x); print(' sreal: ' + sreal.fmt(res))
        res = dreal.exp10m1(x); print(' dreal: ' + dreal.fmt(res))
        res = ereal.exp10m1(x); print(' ereal: ' + ereal.fmt(res))
        res = qreal.exp10m1(x); print(' qreal: ' + qreal.fmt(res))
        res = oreal.exp10m1(x); print(' oreal: ' + oreal.fmt(res))
        if gui.has_xlcalcnet2:
            res = mreal.exp10m1(x); print(' mreal: ' + mreal.fmt(res))
            res = sflint.exp10m1(x); print('sflint: ' + sflint.fmt(res))
            res = dflint.exp10m1(x); print('dflint: ' + dflint.fmt(res))
            res = eflint.exp10m1(x); print('eflint: ' + eflint.fmt(res))
            res = qflint.exp10m1(x); print('qflint: ' + qflint.fmt(res))
            res = oflint.exp10m1(x); print('oflint: ' + oflint.fmt(res))
            res = mflint.exp10m1(x); print('mflint: ' + mflint.fmt(res))
            res = aflint.exp10m1(x); print('aflint: ' + aflint.fmt(res))
        print('</H2>')
        print()
    print('</H1>')
    print()



