def main_tests():
    demo_manual_real()
    demo_expm1_real_ctx()
    demo_expm1_real_explicit()


def demo_manual_real():
    print('<H1 Title="demo_manual_real">')
    #from xlcalcnet import *
    x = -5.1; gui.setdps(90)
    for ctx in gui.ctxlist_real: print(ctx.fmtname + ': ' + ctx.fmt(ctx.expm1(x)))
    print('</H1>')


def demo_expm1_real_ctx():
    print('<H1 Title="demo_expm1_real_ctx">')
    xlist = [-5.1, 8.8]; gui.setdps(90)
    for x in xlist:
        print('<H2 Title="expm1(x); x=' + str(x) + '">')
        for ctx in gui.ctxlist_real:
            res = ctx.expm1(x)
            print(ctx.fmtname + ': ' + ctx.fmt(res))
        print('</H2>')
        print()
    print('</H1>')
    print()


def demo_expm1_real_explicit():
    print('<H1 Title="demo_expm1_real_explicit">')
    xlist = [-5.1, 8.8]; gui.setdps(90)
    for x in xlist:
        print('<H2 Title="expm1(x); x=' + str(x) + '">')
        res = math53.expm1(x); print('math53: ' + math53.fmt(res))
        res = sreal.expm1(x); print(' sreal: ' + sreal.fmt(res))
        res = dreal.expm1(x); print(' dreal: ' + dreal.fmt(res))
        res = ereal.expm1(x); print(' ereal: ' + ereal.fmt(res))
        res = qreal.expm1(x); print(' qreal: ' + qreal.fmt(res))
        res = oreal.expm1(x); print(' oreal: ' + oreal.fmt(res))
        if gui.has_xlcalcnet2:
            res = mreal.expm1(x); print(' mreal: ' + mreal.fmt(res))
            res = sflint.expm1(x); print('sflint: ' + sflint.fmt(res))
            res = dflint.expm1(x); print('dflint: ' + dflint.fmt(res))
            res = eflint.expm1(x); print('eflint: ' + eflint.fmt(res))
            res = qflint.expm1(x); print('qflint: ' + qflint.fmt(res))
            res = oflint.expm1(x); print('oflint: ' + oflint.fmt(res))
            res = mflint.expm1(x); print('mflint: ' + mflint.fmt(res))
            res = aflint.expm1(x); print('aflint: ' + aflint.fmt(res))
        print('</H2>')
        print()
    print('</H1>')
    print()



