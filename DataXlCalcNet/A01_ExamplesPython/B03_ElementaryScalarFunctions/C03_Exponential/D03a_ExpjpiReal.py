def demo_expjpi_real_ctx():
    print('<H1 Title="demo_expjpi_real_ctx">')
    xlist = [-5.1, 8.8]; gui.setdps(90)
    for x in xlist:
        print('<H2 Title="expjpi(x); x=' + str(x) + '">')
